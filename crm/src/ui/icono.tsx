export function Icono({ nombre, className = "size-4", ...resto }: { nombre: string; className?: string; "aria-hidden"?: boolean }) {
  const Componente = iconos[nombre] ?? Circle;
  return <Componente className={className} aria-hidden={resto["aria-hidden"] ?? true} />;
}

/** Cuadro de color con el icono de un objeto. */
export function IconoObjeto({ icono, color, tamano = "md" }: { icono: string; color: string; tamano?: "sm" | "md" | "lg" }) {
  const caja = { sm: "size-6 rounded", md: "size-8 rounded-md", lg: "size-11 rounded-lg" }[tamano];
  const glifo = { sm: "size-3.5", md: "size-4.5", lg: "size-6" }[tamano];
  return (
    <span className={`inline-flex shrink-0 items-center justify-center text-white ${color} ${caja}`}>
      <Icono nombre={icono} className={glifo} />
    </span>
  );
}
